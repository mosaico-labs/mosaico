def make_imu_mcap(meas_time: Time, encoding: str) -> Union[Dict[str, Any], Message]:
    t = meas_time.to_float()

    if encoding == "jsonschema":
        return {
            "header": {
                "stamp": {"sec": meas_time.seconds, "nanosec": meas_time.nanoseconds},
                "frame_id": "imu_link",
            },
            "orientation": {"x": math.sin(t), "y": math.cos(t), "z": 0.0, "w": 1.0},
            "angular_velocity": {
                "x": 0.01 * math.sin(t),
                "y": 0.02 * math.cos(t),
                "z": 0.03,
            },
            "linear_acceleration": {
                "x": 0.0,
                "y": 0.0,
                "z": 9.81 + 0.1 * math.sin(t),
            },
            "linear_acceleration_covariance": [
                0.01 if i % 4 == 0 else 0.0 for i in range(9)
            ],
            "status": 0,
            "calibrated": True,
            "sequence": int(t * 1000) % 65536,
            "temperature_millideg": 25000 + int(100 * math.sin(t)),
            "uptime_ns": meas_time.to_nanoseconds(),
            "drift_estimate": 0.001 * math.sin(t),
            "diagnostic_note": f"imu-sample-{meas_time.to_nanoseconds()}",
        }
    elif encoding == "protobuf":
        msg = _Imu(
            header=_Header(
                stamp=_Stamp(sec=meas_time.seconds, nanosec=meas_time.nanoseconds),
                frame_id="imu_link",
            ),
            orientation=_Quaternion(x=math.sin(t), y=math.cos(t), z=0.0, w=1.0),
            angular_velocity=_Vector3(
                x=0.01 * math.sin(t), y=0.02 * math.cos(t), z=0.03
            ),
            linear_acceleration=_Vector3(x=0.0, y=0.0, z=9.81 + 0.1 * math.sin(t)),
            linear_acceleration_covariance=[
                0.01 if i % 4 == 0 else 0.0 for i in range(9)
            ],
            status=IMU_STATUS_OK,
            calibrated=True,
            sequence=int(t * 1000) % 65536,
            temperature_millideg=25000 + int(100 * math.sin(t)),
            uptime_ns=meas_time.to_nanoseconds(),
            drift_estimate=0.001 * math.sin(t),
            raw_diagnostic=f"imu-sample-{meas_time.to_nanoseconds()}".encode(),
        )
        return msg
    else:
        raise Exception(f"Unsupported encoding '{encoding}'")


