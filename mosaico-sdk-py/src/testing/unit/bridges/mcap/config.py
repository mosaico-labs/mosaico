# ----- JSON Schema definitions -----
# Loaded verbatim from utils/jsonschema/*.schema.json.
# Only object/properties, array/items and the number/integer/boolean/string scalars are used,
# since that is all mosaicolabs' JsonschemaSchemaConverter understands.

_JSONSCHEMA_DIR = Path(__file__).parent / "utils" / "jsonschema"


def _load_jsonschema(name: str) -> Dict[str, Any]:
    return json.loads((_JSONSCHEMA_DIR / f"{name}.schema.json").read_text())


IMU_JSONSCHEMA = _load_jsonschema("imu")
GPS_JSONSCHEMA = _load_jsonschema("gps")
MAGN_JSONSCHEMA = _load_jsonschema("magnetometer")

# ----- Protobuf schema definitions -----
# Message classes generated by protoc from utils/proto/*.proto into
# utils/generated/*_pb2.py (see utils/README.md). make_*_mcap() constructs real
# protobuf messages with these; mcap_protobuf.writer.Writer (used in conftest.py)
# derives the MCAP schema record (name + FileDescriptorSet bytes) from the message's
# own DESCRIPTOR, so nothing else needs to be exposed here.

