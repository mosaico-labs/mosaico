def make_magn_mcap(meas_time: Time, encoding: str) -> Union[Dict[str, Any], Message]:
    t = meas_time.to_float()

    readings = [
        {"axis": "x", "value": 20.0 + math.sin(t), "saturated": False},
        {"axis": "y", "value": -5.0 + math.cos(t), "saturated": False},
        {"axis": "z", "value": 42.0, "saturated": t > 2.5},
    ]

    if encoding == "jsonschema":
        return {
            "header": {
                "stamp": {"sec": meas_time.seconds, "nanosec": meas_time.nanoseconds},
                "frame_id": "magn_link",
            },
            "magnetic_field": {
                "x": 20.0 + math.sin(t),
                "y": -5.0 + math.cos(t),
                "z": 42.0,
            },
            "magnetic_field_covariance": [
                0.02 if i % 4 == 0 else 0.0 for i in range(9)
            ],
            "temperature_celsius": 21.5 + 0.1 * math.sin(t),
            "sensor_id": 7,
            "saturated": t > 2.5,
            "calibration_notes": ["factory-cal", "temp-compensated"],
            "readings": readings,
            "hardware_revision": 3,
            "raw_counter": meas_time.to_nanoseconds() % 1_000_000,
        }
    elif encoding == "protobuf":
        msg = _Magnetometer(
            header=_Header(
                stamp=_Stamp(sec=meas_time.seconds, nanosec=meas_time.nanoseconds),
                frame_id="magn_link",
            ),
            magnetic_field=_Vector3(x=20.0 + math.sin(t), y=-5.0 + math.cos(t), z=42.0),
            magnetic_field_covariance=[0.02 if i % 4 == 0 else 0.0 for i in range(9)],
            temperature_celsius=21.5 + 0.1 * math.sin(t),
            sensor_id=7,
            saturated=t > 2.5,
            calibration_notes=["factory-cal", "temp-compensated"],
            readings=[_AxisReading(**reading) for reading in readings],
            hardware_revision=3,
            raw_counter=meas_time.to_nanoseconds() % 1_000_000,
        )
        return msg
    else:
        raise Exception(f"Unsupported encoding '{encoding}'")


# ----- Time generator -----

START_TIME_S = 0
START_TIME_NS = 0
STEP_NS = 5000000  # 5ms
N_STEPS = 1000  # 0 seconds -> 5 seconds


def time_generator(
    start_sec: int,
    start_nanosec: int,
    step_nanosec: int,
    steps: int,
):
    sec = start_sec
    nsec = start_nanosec

    for _ in range(steps):
        yield Time(seconds=sec, nanoseconds=nsec)

        nsec += step_nanosec
        sec += nsec // 1_000_000_000
        nsec = nsec % 1_000_000_000
