impl GrpcPublicError for mosaicod_facade::Error {
    fn public_message(&self) -> String {
        match self {
            Self::NotFound(_)
            | Self::Unauthorized
            | Self::Unimplemented
            | Self::SessionLocked
            | Self::TopicLocked
            | Self::TopicUnlocked
            | Self::SessionEmpty
            | Self::TopicAlreadyExists(_) => self.to_string(),
            _ => "internal error".to_owned(),
        }
    }

    fn grpc_code(&self) -> tonic::Code {
        match self {
            Self::NotFound(_) => tonic::Code::NotFound,
            Self::Unauthorized => tonic::Code::Unauthenticated,
            Self::Unimplemented => tonic::Code::Unimplemented,
            Self::TopicAlreadyExists(_) => tonic::Code::AlreadyExists,
            Self::SessionLocked | Self::TopicLocked | Self::TopicUnlocked | Self::SessionEmpty => {
                tonic::Code::FailedPrecondition
            }
            _ => tonic::Code::Internal,
        }
    }
}

